// Regenerates packages/shared/src/generated from the Rust types (ts-rs), then writes the barrel file.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function generate(outDir) {
  fs.rmSync(outDir, { recursive: true, force: true });
  const result = spawnSync('cargo', ['test', '--workspace', '--lib', '--quiet'], {
    cwd: root,
    stdio: ['ignore', 'ignore', 'inherit'],
    env: { ...process.env, TS_RS_EXPORT_DIR: outDir },
  });
  if (result.status !== 0) throw new Error('cargo test failed while generating types');
  const names = fs.readdirSync(outDir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.slice(0, -3)).sort();
  const barrel = [
    '// This file was generated by scripts/gen-types.mjs. Do not edit it manually.',
    ...names.map((name) => `export type { ${name} } from './${name}';`),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'index.ts'), barrel);
  return names;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const names = generate(path.join(root, 'packages/shared/src/generated'));
  console.log(`generated ${names.length} types`);
}
